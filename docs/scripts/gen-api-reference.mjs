// Generates docs/reference/admin-api.md from the repository's openapi.json (the management
// API contract). Run with `npm run gen:api`; never edit the generated page by hand.
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(join(here, '../../openapi.json'), 'utf8'));
const out = join(here, '../docs/reference/admin-api.md');

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
// MDX reads { } < > as syntax; escape them in prose (code spans are safe).
const prose = (s) => (s ?? '').replace(/\s+/g, ' ').trim().replace(/[{}<>]/g, (c) => `\\${c}`).replace(/\|/g, '\\|');
const refName = (ref) => ref.split('/').pop();

function typeOf(schema) {
  if (!schema) return '';
  if (schema.$ref) return refName(schema.$ref);
  if (schema.type === 'array') return `${typeOf(schema.items)}[]`;
  if (schema.enum) return schema.enum.join(' \\| ');
  return schema.format ? `${schema.type} (${schema.format})` : (schema.type ?? 'object');
}

function bodyOf(content) {
  if (!content) return null;
  const [mediaType, media] = Object.entries(content)[0];
  return `\`${typeOf(media.schema)}\` (${mediaType})`;
}

const byTag = new Map();
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    const tag = op.tags?.[0] ?? 'other';
    if (!byTag.has(tag)) byTag.set(tag, []);
    byTag.get(tag).push({path, method, op});
  }
}

const lines = [
  '---',
  'sidebar_position: 1',
  'title: Management API',
  'toc_max_heading_level: 2',
  '---',
  '',
  '{/* Generated by scripts/gen-api-reference.mjs from openapi.json. Do not edit by hand. */}',
  '',
  '# Management API',
  '',
  prose(spec.info.description),
  'Everything the UI does goes through it, so scripts can do the same.',
  '',
  '- Base path: `/admin/api`. The OpenAPI document is served at `/admin/api/openapi.json`.',
  '- Authenticate with a personal [API token](../config/cli-and-ci.md#create-an-api-token): `Authorization: Bearer odb_…`.',
  '  Browser sessions also send the `X-XSRF-TOKEN` header for writes.',
  '- Errors are RFC 9457 problems; see [Errors](./errors.md#management-api).',
  '- Published endpoints are not part of this API: each workspace documents its own at `/api/{workspace}/openapi.json`.',
  '',
  `${Object.keys(spec.paths).length} paths, grouped by area.`,
  '',
];

for (const tag of [...byTag.keys()].sort()) {
  lines.push(`## ${tag}`, '');
  const ops = byTag.get(tag).sort((a, b) => a.path.localeCompare(b.path) || METHODS.indexOf(a.method) - METHODS.indexOf(b.method));
  for (const {path, method, op} of ops) {
    lines.push(`### \`${method.toUpperCase()} ${path}\``, '');
    if (op.summary) lines.push(prose(op.summary), '');
    if (op.description && op.description !== op.summary) lines.push(prose(op.description), '');
    const params = (op.parameters ?? []).filter((p) => p.in !== 'header');
    if (params.length) {
      lines.push('| Parameter | In | Type | Required | Description |', '|---|---|---|---|---|');
      for (const p of params) {
        lines.push(`| \`${p.name}\` | ${p.in} | \`${typeOf(p.schema)}\` | ${p.required ? 'yes' : 'no'} | ${prose(p.description)} |`);
      }
      lines.push('');
    }
    const body = bodyOf(op.requestBody?.content);
    if (body) lines.push(`**Body**: ${body}`, '');
    const ok = Object.entries(op.responses ?? {}).find(([code]) => code.startsWith('2'));
    if (ok) {
      const res = bodyOf(ok[1].content);
      lines.push(`**Response ${ok[0]}**: ${res ?? 'no content'}`, '');
    }
  }
}

const schemas = spec.components?.schemas ?? {};
lines.push('## Schemas', '');
for (const name of Object.keys(schemas).sort()) {
  const s = schemas[name];
  lines.push(`### ${name}`, '');
  if (s.description) lines.push(prose(s.description), '');
  const props = Object.entries(s.properties ?? {});
  if (props.length) {
    const required = new Set(s.required ?? []);
    lines.push('| Field | Type | Required | Description |', '|---|---|---|---|');
    for (const [field, p] of props) {
      lines.push(`| \`${field}\` | \`${typeOf(p)}\` | ${required.has(field) ? 'yes' : 'no'} | ${prose(p.description)} |`);
    }
    lines.push('');
  } else if (s.enum) {
    lines.push(`One of: ${s.enum.map((v) => `\`${v}\``).join(', ')}.`, '');
  }
}

writeFileSync(out, lines.join('\n'));
// The Vietnamese site shows the same generated page; without its own copy, links to and from it break there.
const vi = join(here, '../i18n/vi/docusaurus-plugin-content-docs/current/reference/admin-api.md');
mkdirSync(dirname(vi), {recursive: true});
writeFileSync(vi, lines.join('\n'));
console.log(`Wrote ${out}`);
